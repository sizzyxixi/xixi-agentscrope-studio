import { existsSync, mkdirSync, rmSync, cpSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const source = path.join(root, 'vendor/agentscope-web-ui');
function run(args) { const result = spawnSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', args, { cwd: source, stdio: 'inherit' }); if (result.status !== 0) process.exit(result.status || 1); }
if (!existsSync(path.join(source, 'node_modules/.bin/vite'))) run(['ci', '--ignore-scripts']);
run(['run', 'build']);
const output = path.join(root, 'public/agentscope-admin');
rmSync(output, { recursive: true, force: true }); mkdirSync(output, { recursive: true });
cpSync(path.join(source, 'dist'), output, { recursive: true });
cpSync(path.join(source, 'LICENSE'), path.join(output, 'LICENSE'));
cpSync(path.join(source, 'UPSTREAM.json'), path.join(output, 'UPSTREAM.json'));
// Embed the tiny HTML shell so both Next.js and the local Workers runtime can
// serve deep links without requiring runtime filesystem access.
writeFileSync(path.join(root, 'lib/agentscope-admin-shell.ts'), '// Generated by npm run service:ui:build.\nexport const adminHtml = ' + JSON.stringify(readFileSync(path.join(output, 'index.html'), 'utf8')) + ';\n');
